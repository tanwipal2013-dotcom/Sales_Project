SELECT Region,SUM(sales) AS TOTAL_SALES FROM SALES GROUP BY Region ORDER BY TOTAL_SALES DESC ;
----# TOP 5 PROFITABLE PRODUCTS
SELECT Category,SUM(sales) AS TOTAL_SALES FROM SALES GROUP BY Category ORDER BY TOTAL_SALES DESC LIMIT 5;

----# MONTH SALES TREND ----
SELECT DATE_FORMAT(OrderDate,'%M') AS MONTH,SUM(sales) AS TOTAL_SALES FROM SALES GROUP BY MONTH ORDER BY TOTAL_SALES DESC;
----# HIGH DISCOUNT IMPACT ----
